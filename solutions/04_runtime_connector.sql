-- Openflow Retail VHOL — Act 3: Gen2 runtime + PostgreSQL CDC connector (SQL, no wizard)
-- Source: notebooks/02-openflow-gen2-runtime-connector.ipynb + docs "Configure a gen 2 connector with SQL"
-- Prereq: deployment SPCS_SOM is ACTIVE (SHOW OPENFLOW DEPLOYMENTS).
-- The attendee only asks for the connector; CoCo checks for the runtime and creates it here first if it is missing.

USE ROLE ACCOUNTADMIN;
GRANT READ ON SECRET RETAIL_HOL_ADMIN.SECRETS.RETAIL_HOL_PG_PASSWORD TO ROLE POSTGRES_INGEST_SERVICE_ROLE;

-- 1. Runtime (2-5 min to ACTIVE)
USE ROLE OPENFLOW_ADMIN;
USE DATABASE OPENFLOW_DB;
USE SCHEMA OPENFLOW_SCHEMA;

CREATE OPENFLOW RUNTIME IF NOT EXISTS OPENFLOW_DB.OPENFLOW_SCHEMA.POSTGRES_RUNTIME_SOM
  IN DEPLOYMENT SPCS_SOM
  NODE_TYPE = SMALL            -- S1 (1 CPU, 4 GB heap) is plenty for 5 tables; resize with SET NODE_TYPE_TIER = 'S2'|'S3'
  MIN_NODES = 1
  MAX_NODES = 1
  EXECUTE_AS_ROLE = POSTGRES_INGEST_SERVICE_ROLE
  EXTERNAL_ACCESS_INTEGRATIONS = (RETAIL_HOL_POSTGRES_EAI)
  DISPLAY_NAME = 'POSTGRES_RUNTIME_SOM'
  COMMENT = 'SOM RUNTIME FOR INGESTING FROM SNOWFLAKE POSTGRES';

-- Checkpoint R: block until ACTIVE (returns 'OK'; on timeout re-run this SELECT, never the CREATE)
SELECT SYSTEM$WAIT_FOR_OPENFLOW_RUNTIME_STATUS(600, 'ACTIVE', 'OPENFLOW_DB.OPENFLOW_SCHEMA.POSTGRES_RUNTIME_SOM');

-- 2. Cost control (suspend 5 PM / resume 6 AM Pacific)
USE ROLE ACCOUNTADMIN;
CREATE TASK IF NOT EXISTS OPENFLOW_DB.OPENFLOW_SCHEMA.SUSPEND_POSTGRES_RUNTIME_SOM
  WAREHOUSE = RETAIL_HOL_WH
  SCHEDULE = 'USING CRON 0 17 * * * America/Los_Angeles'
AS
  ALTER OPENFLOW RUNTIME OPENFLOW_DB.OPENFLOW_SCHEMA.POSTGRES_RUNTIME_SOM SUSPEND;
CREATE TASK IF NOT EXISTS OPENFLOW_DB.OPENFLOW_SCHEMA.RESUME_POSTGRES_RUNTIME_SOM
  WAREHOUSE = RETAIL_HOL_WH
  SCHEDULE = 'USING CRON 0 6 * * * America/Los_Angeles'
AS
  ALTER OPENFLOW RUNTIME OPENFLOW_DB.OPENFLOW_SCHEMA.POSTGRES_RUNTIME_SOM RESUME;
-- Tasks are created SUSPENDED; ALTER TASK ... RESUME to enable.

-- 3. Connector from the gen 2 catalog definition
USE ROLE OPENFLOW_ADMIN;
USE DATABASE OPENFLOW_DB;
USE SCHEMA OPENFLOW_SCHEMA;
SHOW OPENFLOW CONNECTOR DEFINITIONS LIKE '%POSTGRES%';

CREATE OPENFLOW CONNECTOR IF NOT EXISTS POSTGRES_INGEST
  IN RUNTIME POSTGRES_RUNTIME_SOM
  FROM DEFINITION OPENFLOW_POSTGRES_CDC
  DISPLAY_NAME = 'POSTGRES_INGEST';

-- 4. Configure: download -> edit -> upload -> commit.
--    In the lab, steps 3-5 run via scripts/configure_connector.py (verified end to end).
--    The JDBC jar (postgresql-42.7.5.jar) is PUT next to config.json; see references/connector_config.md.
LS 'snow://openflow_connector/OPENFLOW_DB.OPENFLOW_SCHEMA.POSTGRES_INGEST/versions/live';
GET 'snow://openflow_connector/OPENFLOW_DB.OPENFLOW_SCHEMA.POSTGRES_INGEST/versions/live/config.json'
  'file://./connector/';
-- edit connector/config.json (values in references/connector_config.md), then:
PUT 'file://./connector/config.json'
  'snow://openflow_connector/OPENFLOW_DB.OPENFLOW_SCHEMA.POSTGRES_INGEST/versions/live/'
  AUTO_COMPRESS = FALSE OVERWRITE = TRUE;
ALTER OPENFLOW CONNECTOR POSTGRES_INGEST COMMIT;
SELECT SYSTEM$WAIT_FOR_STABLE_OPENFLOW_CONNECTORS(600, 'POSTGRES_INGEST');

-- 5. Start (initial snapshot, then continuous CDC from the WAL)
ALTER OPENFLOW CONNECTOR POSTGRES_INGEST START;
SELECT SYSTEM$WAIT_FOR_OPENFLOW_CONNECTOR_STATUS(600, 'RUNNING', 'OPENFLOW_DB.OPENFLOW_SCHEMA.POSTGRES_INGEST');  -- STARTING -> RUNNING, 10 min

-- Checkpoint C: Bronze Iceberg tables landed
USE ROLE ACCOUNTADMIN;
SHOW ICEBERG TABLES IN SCHEMA RETAIL_HOL_ICEBERG.BRONZE;

-- Troubleshooting: recent runtime errors (full observability queries: 04b_observability.sql)
SELECT timestamp, TRY_PARSE_JSON(value):formattedMessage::STRING AS message
FROM OPENFLOW_DB.OPENFLOW_SCHEMA.EVENTS
WHERE timestamp > DATEADD('minutes', -30, SYSDATE()) AND record_type = 'LOG'
  AND TRY_PARSE_JSON(value):level::STRING = 'ERROR'
ORDER BY timestamp DESC LIMIT 20;
