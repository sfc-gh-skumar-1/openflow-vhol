-- Openflow Retail VHOL — Cleanup. Run in order; each step must finish before the next.
-- SUSPEND and TERMINATE are asynchronous: re-run the SHOW check until the status is reached,
-- otherwise DROP fails with "DROP not allowed while ... is in TERMINATING status".
-- DESTRUCTIVE: drops the connector, runtime, deployment, Postgres instance and all lab databases.
USE ROLE ACCOUNTADMIN;
-- Pre-cleanup checks: use SHOW / DESCRIBE (metadata, no warehouse needed). Queries that need compute must run
-- BEFORE RETAIL_HOL_WH is dropped at the end of this file; USE WAREHOUSE RETAIL_HOL_WH if the session has none.

ALTER TASK IF EXISTS OPENFLOW_DB.OPENFLOW_SCHEMA.SUSPEND_POSTGRES_RUNTIME_SOM SUSPEND;
ALTER TASK IF EXISTS OPENFLOW_DB.OPENFLOW_SCHEMA.RESUME_POSTGRES_RUNTIME_SOM SUSPEND;
ALTER ALERT IF EXISTS OPENFLOW_DB.OPENFLOW_SCHEMA.POSTGRES_INGEST_TABLE_FAILURE_ALERT SUSPEND;  -- dropped with OPENFLOW_DB
-- Stop scripts/cdc_demo.py --continuous first (Ctrl+C) if it is still running.

-- Connector
ALTER OPENFLOW CONNECTOR OPENFLOW_DB.OPENFLOW_SCHEMA.POSTGRES_INGEST STOP;
ALTER OPENFLOW CONNECTOR OPENFLOW_DB.OPENFLOW_SCHEMA.POSTGRES_INGEST TERMINATE;
SHOW OPENFLOW CONNECTORS LIKE 'POSTGRES_INGEST' IN SCHEMA OPENFLOW_DB.OPENFLOW_SCHEMA;  -- wait: status TERMINATED (~1 min)
DROP OPENFLOW CONNECTOR OPENFLOW_DB.OPENFLOW_SCHEMA.POSTGRES_INGEST;

-- Runtime
ALTER OPENFLOW RUNTIME OPENFLOW_DB.OPENFLOW_SCHEMA.POSTGRES_RUNTIME_SOM SUSPEND;
SHOW OPENFLOW RUNTIMES LIKE 'POSTGRES_RUNTIME_SOM' IN SCHEMA OPENFLOW_DB.OPENFLOW_SCHEMA;  -- wait: SUSPENDED (~1 min)
ALTER OPENFLOW RUNTIME OPENFLOW_DB.OPENFLOW_SCHEMA.POSTGRES_RUNTIME_SOM TERMINATE;
SHOW OPENFLOW RUNTIMES LIKE 'POSTGRES_RUNTIME_SOM' IN SCHEMA OPENFLOW_DB.OPENFLOW_SCHEMA;  -- wait: TERMINATED (~1-2 min)
DROP OPENFLOW RUNTIME OPENFLOW_DB.OPENFLOW_SCHEMA.POSTGRES_RUNTIME_SOM;

-- Deployment
ALTER OPENFLOW DEPLOYMENT SPCS_SOM TERMINATE;
SHOW OPENFLOW DEPLOYMENTS LIKE 'SPCS_SOM';  -- wait: status column (3rd) TERMINATED (can take 10-20 min)
DROP OPENFLOW DEPLOYMENT IF EXISTS SPCS_SOM;

-- Postgres source
DROP POSTGRES INSTANCE IF EXISTS RETAIL_HOL_PG;

-- Data + admin objects
DROP AGENT IF EXISTS RETAIL_HOL_ICEBERG.GOLD_MANAGED_ICEBERG.RETAIL_ANALYST_AGENT;
DROP DATABASE IF EXISTS RETAIL_HOL_ICEBERG;
DROP DATABASE IF EXISTS OPENFLOW_DB;
DROP EXTERNAL ACCESS INTEGRATION IF EXISTS RETAIL_HOL_POSTGRES_EAI;
DROP NETWORK POLICY IF EXISTS RETAIL_HOL_NETWORK_POLICY;
DROP DATABASE IF EXISTS RETAIL_HOL_ADMIN;
DROP WAREHOUSE IF EXISTS RETAIL_HOL_WH;
ALTER USER IF EXISTS VHOLUSER UNSET DEFAULT_WAREHOUSE;  -- it pointed at RETAIL_HOL_WH
DROP ROLE IF EXISTS POSTGRES_INGEST_SERVICE_ROLE;
DROP ROLE IF EXISTS OPENFLOW_ADMIN;
DROP ROLE IF EXISTS RETAIL_HOL_ROLE;
