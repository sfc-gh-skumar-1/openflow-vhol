-- Openflow Retail VHOL — Act 1b: Openflow Gen2 deployment (kick off FIRST, ~15 min to ACTIVE)
-- Source: notebooks/00-openflow-gen2-deployment.ipynb. Requires 01_environment.sql.

USE ROLE ACCOUNTADMIN;
SET MY_USER = CURRENT_USER();

CREATE DATABASE IF NOT EXISTS OPENFLOW_DB;
CREATE SCHEMA IF NOT EXISTS OPENFLOW_DB.OPENFLOW_SCHEMA;

CREATE ROLE IF NOT EXISTS OPENFLOW_ADMIN COMMENT = 'Manages Openflow Gen2 (SOM) infrastructure';
GRANT ROLE OPENFLOW_ADMIN TO USER IDENTIFIER($MY_USER);
-- Also into the SYSADMIN hierarchy (same pattern as RETAIL_HOL_ROLE), so the Snowsight admin login
-- (e.g. the event's EVENT USER, not VHOLuser) can pick OPENFLOW_ADMIN in the UI for the wizard/dashboard.
GRANT ROLE OPENFLOW_ADMIN TO ROLE SYSADMIN;

ALTER USER IDENTIFIER($MY_USER) SET DEFAULT_SECONDARY_ROLES = ('ALL');

-- Account-level: allow creating deployments and compute pools
GRANT CREATE OPENFLOW DEPLOYMENT ON ACCOUNT TO ROLE OPENFLOW_ADMIN;
GRANT CREATE COMPUTE POOL ON ACCOUNT TO ROLE OPENFLOW_ADMIN;

-- Database-level: access to the Openflow database
GRANT USAGE ON DATABASE OPENFLOW_DB TO ROLE OPENFLOW_ADMIN;

-- Schema-level: create runtimes, connectors, and event tables
GRANT USAGE ON SCHEMA OPENFLOW_DB.OPENFLOW_SCHEMA TO ROLE OPENFLOW_ADMIN;
GRANT CREATE OPENFLOW RUNTIME ON SCHEMA OPENFLOW_DB.OPENFLOW_SCHEMA TO ROLE OPENFLOW_ADMIN;
GRANT CREATE OPENFLOW CONNECTOR ON SCHEMA OPENFLOW_DB.OPENFLOW_SCHEMA TO ROLE OPENFLOW_ADMIN;
GRANT CREATE EVENT TABLE ON SCHEMA OPENFLOW_DB.OPENFLOW_SCHEMA TO ROLE OPENFLOW_ADMIN;

USE ROLE ACCOUNTADMIN;

-- Create the runtime service role
CREATE ROLE IF NOT EXISTS POSTGRES_INGEST_SERVICE_ROLE;

-- OPENFLOW_ADMIN needs this role to assign EXECUTE_AS_ROLE during runtime creation
GRANT ROLE POSTGRES_INGEST_SERVICE_ROLE TO ROLE OPENFLOW_ADMIN;

-- Access to the destination database (connector will create schemas and tables here)
GRANT USAGE ON DATABASE RETAIL_HOL_ICEBERG TO ROLE POSTGRES_INGEST_SERVICE_ROLE;
GRANT CREATE SCHEMA ON DATABASE RETAIL_HOL_ICEBERG TO ROLE POSTGRES_INGEST_SERVICE_ROLE;

-- Access to the secret's database and schema
GRANT USAGE ON DATABASE RETAIL_HOL_ADMIN TO ROLE POSTGRES_INGEST_SERVICE_ROLE;
GRANT USAGE ON SCHEMA RETAIL_HOL_ADMIN.SECRETS TO ROLE POSTGRES_INGEST_SERVICE_ROLE;

-- Warehouse access for processing
GRANT USAGE, OPERATE ON WAREHOUSE RETAIL_HOL_WH TO ROLE POSTGRES_INGEST_SERVICE_ROLE;

-- External Access Integration for network connectivity to Postgres
GRANT USAGE ON INTEGRATION RETAIL_HOL_POSTGRES_EAI TO ROLE POSTGRES_INGEST_SERVICE_ROLE;

USE ROLE OPENFLOW_ADMIN;

CREATE OPENFLOW DEPLOYMENT IF NOT EXISTS SPCS_SOM
  DEPLOYMENT_TYPE = 'SNOWFLAKE'
  DISPLAY_NAME = SPCS_SOM
  COMMENT = 'SPCS_SOM';

-- Create the Events table and attach it to the deployment
USE ROLE OPENFLOW_ADMIN;

CREATE EVENT TABLE IF NOT EXISTS OPENFLOW_DB.OPENFLOW_SCHEMA.EVENTS;

ALTER OPENFLOW DEPLOYMENT SPCS_SOM SET
  EVENT_TABLE = OPENFLOW_DB.OPENFLOW_SCHEMA.EVENTS;

-- Checkpoint D (re-run until state = ACTIVE)
SHOW OPENFLOW DEPLOYMENTS;
